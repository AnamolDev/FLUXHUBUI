/*
 * Bundles every .lua file under src/ into dist/FluxHub.lua.
 *
 * Why a bundle exists: a hub consumes a UI library with one line,
 *   loadstring(game:HttpGet("https://raw.githubusercontent.com/.../dist/FluxHub.lua"))()
 * and a single loadstring cannot resolve a folder of ModuleScripts. The source tree stays
 * modular for contributors; this script flattens it into a self-contained module registry
 * where each module keeps its normal `require("Flux/…")` calls.
 *
 * Usage: node tools/build.mjs [--out dist/FluxHub.lua]
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync, existsSync } from "node:fs";
import { dirname, join, posix, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const srcRoot = join(root, "src");

const argv = process.argv.slice(2);
const outFlag = argv.indexOf("--out");
const outFile = outFlag === -1 ? join(root, "dist", "FluxHub.lua") : resolve(root, argv[outFlag + 1]);

function walk(dir) {
  const found = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      found.push(...walk(full));
    } else if (entry.endsWith(".lua")) {
      found.push(full);
    }
  }
  return found.sort();
}

/** src/Utilities/Signal.lua -> "Flux/Utilities/Signal" */
function moduleId(file) {
  const rel = relative(srcRoot, file).split("\\").join("/");
  return posix.join("Flux", rel.replace(/\.lua$/, ""));
}

/** Mode directives (--!strict, --!nonstrict) are only legal as the first line of a module.
 *  Inside a registry function they would be a syntax error, so they are lifted out and
 *  recorded instead. */
function stripModeDirective(body) {
  const match = body.match(/^--!(strict|nonstrict|nocheck)[ \t]*\r?\n/);
  if (!match) {
    return { body, mode: null };
  }
  return { body: body.slice(match[0].length), mode: match[1] };
}

const files = walk(srcRoot);
const modules = files.map((file) => {
  const raw = readFileSync(file, "utf8");
  const { body, mode } = stripModeDirective(raw);
  return {
    id: moduleId(file),
    path: relative(root, file).split("\\").join("/"),
    body,
    mode,
  };
});

const version = existsSync(join(root, "VERSION"))
  ? readFileSync(join(root, "VERSION"), "utf8").trim()
  : "0.0.0";

const declaredModes = modules.filter((m) => m.mode !== null);

const header = `--[[
	Flux Hub UI Library v${version}

	Generated by tools/build.mjs from ${modules.length} modules under src/. Do not edit this
	file; edit the source and rebuild.

		consume:
			local Flux = loadstring(game:HttpGet(url))()
			local Window = Flux:CreateWindow({ Title = "Flux Hub" })

		strict-mode notes recorded from the source tree: ${declaredModes.length}/${modules.length} modules
		declare a mode directive. See src/Types/Flux.d.luau for the public type surface.
]]

local FluxRegistry = {}
local FluxLoaded = {}

local function fluxRequire(path)
	local cached = FluxLoaded[path]
	if cached ~= nil then
		return cached
	end

	local factory = FluxRegistry[path]
	if factory == nil then
		error("Flux: unknown module " .. tostring(path), 2)
	end

	local ok, result = pcall(factory, fluxRequire)
	if not ok then
		error("Flux: module " .. tostring(path) .. " failed to load: " .. tostring(result), 2)
	end

	FluxLoaded[path] = result
	return result
end

`;

const registry = modules
  .map((module) => {
    const indented = module.body
      .split("\n")
      .map((line) => (line.length === 0 ? "" : "\t" + line))
      .join("\n")
      .trimEnd();

    return `-- ${module.path}\nFluxRegistry["${module.id}"] = function(require)\n${indented}\nend\n`;
  })
  .join("\n");

const output = `${header}${registry}\nreturn fluxRequire("Flux/init")\n`.replace(
  /__FLUX_VERSION__/g,
  JSON.stringify(version),
);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, output, "utf8");

const bytes = Buffer.byteLength(output, "utf8");
console.log(`built ${outFile}`);
console.log(`  modules: ${modules.length}`);
console.log(`  size: ${(bytes / 1024).toFixed(1)} KB`);
